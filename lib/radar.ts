// Token Launch Radar — model "radar-2".
//
// One sealed DefiLlama snapshot in, one ranked board out. The board ranks only
// protocols whose record carries no token (no market cap, no CoinGecko id, no
// symbol): "records no token" is the snapshot's claim, never proof the protocol
// has none. Protocols whose token already trades are kept apart in the Live
// view, shown at the market's own value, never mixed into the ranking.
//
// Implied value is derived from the snapshot's own figures only — no name is
// ever special-cased, and the same function scores every row:
//
//   implied = tvl_usd
//           x categoryMultiple   (the category's own market multiple, see below)
//           x growthMultiplier   (7-day TVL change, clamped)
//           x maturityMultiplier (how long the protocol has run with no token)
//           x breadthMultiplier  (how many chains its TVL sits on)
//
// categoryMultiple is the part that makes this radar a radar instead of a
// TVL list: for each category it is the MEDIAN market-cap/TVL ratio of the
// live-token protocols of that same category inside this very snapshot
// (at least 3 comparables, otherwise the snapshot-wide median), clamped to
// [0.02, 1.50] so one outlier cannot set a category's price. A lending
// protocol is therefore priced like lending protocols trade, a DEX like
// DEXes trade — the market's own verdict, read off the snapshot, not a
// number typed in by hand. The multiples are recomputed on every run from
// whatever snapshot is fed in, and the dashboard prints the table.
//
//   growth   = clamp(change_7d, -50, +100) per cent;  missing change counts as 0
//   growthMultiplier   = 1 + growth / 100 * 0.40
//   maturityMultiplier = 0.70 + min(age_days, 1460) / 1460 * 0.30
//                        (age unknown: 0.85 — a protocol tracked for four years
//                        with no token has survived longer than one tracked
//                        for four months, and the market prices survival)
//   breadthMultiplier  = 1 + 0.04 * min(chains - 1, 5)
//
// The board covers the snapshot's whole watchlist (the floor, never the
// ceiling) plus every other rankable pre-token protocol below the floor,
// by TVL. Rank 1 is the highest implied value.

/** One protocol entry: exactly the ten fields the sealed snapshot carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them. */
export interface ModelConstants {
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_multiplier: number;
  breadth_per_chain: number;
  breadth_max_chains: number;
  multiple_floor: number;
  multiple_cap: number;
  min_comparables: number;
}

export const MODEL: ModelConstants = {
  growth_weight: 0.4,
  growth_floor: -50,
  growth_cap: 100,
  maturity_floor: 0.7,
  maturity_range: 0.3,
  maturity_days: 1460,
  unknown_age_multiplier: 0.85,
  breadth_per_chain: 0.04,
  breadth_max_chains: 5,
  multiple_floor: 0.02,
  multiple_cap: 1.5,
  min_comparables: 3,
};

